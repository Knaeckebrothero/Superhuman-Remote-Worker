# The job description is free text — typed by users, generated by the loop
# engine and automations — and lands in a JSON blob nested inside the VM
# template's cloud-init `userData: |` block scalar. Raw substitution there is
# unsafe twice over: a newline puts the continuation at column 1, dedenting out
# of the block scalar and destroying the manifest (job 4435994d), while a quote
# or backslash leaves valid YAML wrapping a corrupt job-config.json that
# management-daemon.py discards with only a log.warning.
#
# Capped because the whole userData block has a hard 2048-byte KubeVirt limit
# (inline cloudInitNoCloud) with only ~350 bytes of headroom. Nothing in the VM
# reads this field — management-daemon.py is job-config.json's only consumer and
# never looks at `description` — so truncating it costs nothing.
MAX_DESCRIPTION_LEN = 200

_OWNER_KINDS = frozenset({"job", "thread"})
_PROVISION_GENERATION_ANNOTATION = "srw.io/provision-generation"


@dataclass(frozen=True, slots=True)
class VMTeardownIdentity:
    """Immutable VM incarnation captured before a destructive lifecycle call."""

    provision_generation: str
    vm_uid: str | None
    rootdisk_pvc_uid: str | None


@dataclass(frozen=True, slots=True)
class VMTeardownResult:
    """Bounded result distinguishing completion from identity supersession."""

    disposition: str
    deleted: bool


@dataclass(frozen=True, slots=True)
class _VMTeardownProbe:
    """Authenticated observation used to reconcile an ambiguous delete."""

    disposition: str
    identity: VMTeardownIdentity | None = None
    rootdisk_identity_known: bool = False


def _escape_for_job_config(description: str) -> str:
    """JSON-escape a description for the template's job-config.json blob.

    Returns the escaped body without json.dumps' surrounding quotes, since the
    template supplies those. Shrinks the raw text until its *escaped* form fits
    MAX_DESCRIPTION_LEN, so an escape sequence is never cut in half.
    """
    raw = description[:MAX_DESCRIPTION_LEN]
    while raw and len(json.dumps(raw)[1:-1]) > MAX_DESCRIPTION_LEN:
        raw = raw[:-1]
    return json.dumps(raw)[1:-1]


def _owner_identity(job_config: dict) -> tuple[str, str]:
    """Return the validated, full application owner identity for one VM."""

    owner_kind = job_config.get("entity_type", "job")
    owner_id = job_config.get("job_id")
    if owner_kind not in _OWNER_KINDS:
        raise ValueError("entity_type must be 'job' or 'thread'")
    if (
        not isinstance(owner_id, str)
        or not owner_id
        or owner_id != owner_id.strip()
        or len(owner_id) > 63
        or any(character.isspace() for character in owner_id)
    ):
        raise ValueError("job_id is not a valid Kubernetes owner label")
    return owner_kind, owner_id


def _stamp_owner_identity(manifest: dict, owner_kind: str, owner_id: str) -> None:
    """Stamp VM, VMI-template, and DataVolume/PVC-propagated owner labels."""

    def stamp(metadata: dict) -> None:
        labels = metadata.setdefault("labels", {})
        labels["srw.io/owner-kind"] = owner_kind
        labels["srw.io/owner-id"] = owner_id

    stamp(manifest.setdefault("metadata", {}))
    spec = manifest.setdefault("spec", {})
    template = spec.setdefault("template", {})
    stamp(template.setdefault("metadata", {}))
    data_volume_templates = spec.get("dataVolumeTemplates", [])
    if isinstance(data_volume_templates, list):
        for data_volume_template in data_volume_templates:
            if isinstance(data_volume_template, dict):
                stamp(data_volume_template.setdefault("metadata", {}))


def _provision_generation(value: object) -> str | None:
    if not isinstance(value, str) or len(value) != 36:
        return None
    try:
        parsed = UUID(value)
    except (AttributeError, TypeError, ValueError):
        return None
    return value if str(parsed) == value else None


def _stamp_provision_generation(manifest: dict, generation: str) -> None:
    metadata = manifest.setdefault("metadata", {})
    metadata.setdefault("annotations", {})[_PROVISION_GENERATION_ANNOTATION] = (
        generation
    )
    template_metadata = (
        manifest.setdefault("spec", {})
        .setdefault("template", {})
        .setdefault("metadata", {})
    )
    template_metadata.setdefault("annotations", {})[
        _PROVISION_GENERATION_ANNOTATION
    ] = generation


def _admitted_provision_generation(value: object) -> str | None:
    if not isinstance(value, Mapping):
        return None
    metadata = value.get("metadata")
    if not isinstance(metadata, Mapping):
        return None
    annotations = metadata.get("annotations")
    if not isinstance(annotations, Mapping):
        return None
    return _provision_generation(annotations.get(_PROVISION_GENERATION_ANNOTATION))


def _safe_vm_uid(value: object) -> str | None:
    if (
        not isinstance(value, str)
        or not value
        or value != value.strip()
        or len(value) > 256
        or any(character.isspace() for character in value)
    ):
        return None
    return value


def _admitted_vm_uid(value: object, *, expected_name: str) -> str | None:
    """Extract the immutable VM UID from one admitted Kubernetes object."""

    if not isinstance(value, Mapping):
        return None
    metadata = value.get("metadata")
    if not isinstance(metadata, Mapping) or metadata.get("name") != expected_name:
        return None
    return _safe_vm_uid(metadata.get("uid"))


def _admitted_pvc_uid(
    value: object,
    *,
    expected_name: str,
    expected_owner_id: str,
    expected_owner_kind: str,
) -> str | None:
    """Extract an immutable UID only from the exact provisioned root claim."""

    if isinstance(value, Mapping):
        metadata = value.get("metadata")
    else:
        metadata = getattr(value, "metadata", None)
    if isinstance(metadata, Mapping):
        name = metadata.get("name")
        uid = metadata.get("uid")
        labels = metadata.get("labels")
    else:
        name = getattr(metadata, "name", None)
        uid = getattr(metadata, "uid", None)
        labels = getattr(metadata, "labels", None)
    if name != expected_name or not isinstance(labels, Mapping):
        return None
    if (
        labels.get("srw.io/owner-kind") != expected_owner_kind
        or labels.get("srw.io/owner-id") != expected_owner_id
    ):
        return None
    return _safe_vm_uid(uid)


def _extract_vm_context(job: dict) -> dict:
    """Extract the vm sub-dict from a job's context."""
    ctx = job.get("context") or {}
    if isinstance(ctx, str):
        try:
            ctx = json.loads(ctx)
        except (json.JSONDecodeError, TypeError):
            ctx = {}
    return ctx.get("vm", {})


def _http_lifecycle_query(
    payload: Mapping[str, Any], *, operation: str, secret: bytes | None
) -> dict[str, str]:
    """Encode an authenticated envelope into stable HTTP query fields."""

    signed = sign_payload(
        payload,
        direction="request",
        operation=operation,
        secret=secret,
    )
    auth = signed.get(AUTH_FIELD)
    if not isinstance(auth, Mapping):
        return {}
    return {
        "lifecycle_auth": str(auth["signature"]),
        "lifecycle_auth_issued_at": str(auth["issued_at"]),
        "lifecycle_auth_request_id": str(auth["request_id"]),
    }


def vm_persistent_rootdisk_enabled() -> bool:
    """Whether the VM controller keeps rootdisks across VM deletion.

    Mirrors the controller's own ``VM_PERSISTENT_ROOTDISK``; the orchestrator
    cannot observe the controller's config, so the two are set from the same
    Helm value and this is the orchestrator's copy. Read at call time rather
    than import so tests (and a config reload) see changes.

    **Enable the controller first.** Turning this on against a controller that
    still cascade-deletes disks would let VM session suspend tear a workspace
    down believing the files survive — they would not. The reverse order is
    harmless: the controller keeps disks nobody asks it to keep, and the
    delete-status handler records what actually happened either way.

    knowledge-base/knowledge/features/vm_persistent_rootdisk.md
    """
    return os.environ.get("VM_PERSISTENT_ROOTDISK", "false").strip().lower() in (
        "1",
        "true",
        "yes",
    )


class VMProvisioner:
    """Unified VM provisioner with automatic backend selection.

    Uses NATS bridge when available (cross-cluster), falls back to direct
    Kubernetes API calls (same-cluster). Control commands (freeze/resume/
    terminate) require NATS since they target the management daemon inside
    the VM.
    """

    def __init__(self):
        self._db: Optional[Any] = None
        self._snapshot_service: Optional[Any] = None
        self._k8s: Optional[Any] = None
        self._core_k8s: Optional[Any] = None
        self._k8s_available: bool = False
        self._template_text: str = ""
        self._vm_namespace: str = os.environ.get("VM_NAMESPACE", "agent-vms")
        self._default_vm_image: str = os.environ.get(
            "DEFAULT_VM_IMAGE",
            "ghcr.io/knaeckebrothero/superhuman-remote-worker-agent-vm-base:latest",
        )
        # HTTP controller transport (same-cluster, no NATS).
        self._controller_url: str = os.environ.get("VM_CONTROLLER_URL", "").rstrip("/")
        self._http_client: Optional[httpx.AsyncClient] = None
        self._http_timeout: float = float(os.environ.get("VM_CONTROLLER_TIMEOUT", "30"))
        self._lifecycle_hmac_secret = configured_secret()

    @property
    def is_available(self) -> bool:
        """True if any VM provisioning backend is available."""
        return (
            nats_bridge.is_available
            or self._http_available
            or self._k8s_available
            or self._docker_available
        )

    @property
    def _http_available(self) -> bool:
        """True if a co-located VM controller HTTP endpoint is configured."""
        return bool(self._controller_url)

    @property
    def _docker_available(self) -> bool:
        """True if QEMU-in-Docker VMs are configured."""
        from .docker_provisioner import docker_provisioner

        return len(docker_provisioner.vm_hosts) > 0

    @property
    def mode(self) -> Optional[str]:
        """Current provisioning mode: 'nats', 'http', 'direct', 'docker', or None."""
        if nats_bridge.is_available:
            return "nats"
        if self._http_available:
            return "http"
        if self._k8s_available:
            return "direct"
        if self._docker_available:
            return "docker"
        return None

    async def _current_provision_generation(
        self, entity_type: str, entity_id: str
    ) -> str | None:
        """Read the durable generation used to fence lifecycle commands."""

        if not self._db:
            return None
        try:
            if entity_type == "thread":
                row = await self._db.get_thread(entity_id)
                metadata = row.get("metadata") if isinstance(row, Mapping) else None
                if isinstance(metadata, str):
                    metadata = json.loads(metadata)
                context = metadata.get("vm") if isinstance(metadata, Mapping) else None
            else:
                row = await self._db.get_job(entity_id)
                context = _extract_vm_context(row) if isinstance(row, dict) else None
            if not isinstance(context, Mapping):
                return None
            return _provision_generation(context.get("provision_generation"))
        except Exception:
            logger.exception(
                "Could not read current VM provision generation for %s %s",
                entity_type,
                entity_id,
            )
            return None

    async def _set_context_if_generation(
        self,
        entity_type: str,
        entity_id: str,
        generation: str,
        updates: dict,
    ) -> bool:
        if entity_type == "thread":
            return await self._set_thread_vm_context_if_generation(
                entity_id, generation, updates
            )
        return await self._set_vm_context_if_generation(entity_id, generation, updates)

    async def _persist_status_identity(
        self, entity_type: str, entity_id: str, data: Mapping[str, Any]
    ) -> bool:
        """Persist query-discovered identities only from authenticated evidence."""

        if data.get("_identity_authenticated") is not True:
            return False
        generation = _provision_generation(data.get("provision_generation"))
        if generation is None:
            return False
        updates: dict[str, Any] = {}
        for key in ("vm_name", "namespace"):
            if isinstance(data.get(key), str):
                updates[key] = data[key]
        vm_uid = _safe_vm_uid(data.get("vm_uid"))
        if vm_uid is not None:
            updates.update(
                {
                    "vm_uid": vm_uid,
                    "identity_authenticated": True,
                    "identity_provision_generation": generation,
                }
            )
        if (root_uid := _safe_vm_uid(data.get("rootdisk_pvc_uid"))) is not None:
            updates["rootdisk_pvc_uid"] = root_uid
        return await self._set_context_if_generation(
            entity_type,
            entity_id,
            generation,
            updates,
        )

    # =========================================================================
    # Lifecycle
    # =========================================================================

    def connect(
        self,
        db: Any,
        snapshot_service: Optional[Any] = None,
    ) -> None:
        """Initialize the provisioner.

        Args:
            db: PostgresDB instance for job context updates.
            snapshot_service: Optional SnapshotService for archival before deletion.
        """
        self._db = db
        self._snapshot_service = snapshot_service
        self._init_k8s()

        if self._http_available:
            self._http_client = httpx.AsyncClient(
                base_url=self._controller_url,
                timeout=self._http_timeout,
            )

        if nats_bridge.is_available:
            logger.info("VM provisioner ready: NATS mode")
        elif self._http_available:
            logger.info(
                "VM provisioner ready: HTTP mode (controller=%s)",
                self._controller_url,
            )
        elif self._k8s_available:
            logger.info(
                "VM provisioner ready: direct K8s mode (namespace=%s)",
                self._vm_namespace,
            )
        else:
            logger.info(
                "VM provisioner: no backend available "
                "(NATS, controller URL, and K8s all unavailable)"
            )

    async def disconnect(self) -> None:
        """Close the HTTP client (if any)."""
        if self._http_client is not None:
            try:
                await self._http_client.aclose()
            except Exception:
                logger.debug("Error closing VM controller HTTP client", exc_info=True)
            self._http_client = None

    def _init_k8s(self) -> None:
        """Try to initialize the Kubernetes client for direct provisioning."""
        if not K8S_AVAILABLE:
            return

        try:
            try:
                k8s_config.load_incluster_config()
            except k8s_config.ConfigException:
                try:
                    k8s_config.load_kube_config()
                except k8s_config.ConfigException:
                    logger.debug(
                        "Kubernetes not available (no in-cluster or kubeconfig)"
                    )
                    return

            self._k8s = k8s_client.CustomObjectsApi()
            self._core_k8s = k8s_client.CoreV1Api()
            self._load_template()
        except Exception as e:
            logger.debug("Direct K8s VM provisioning not available: %s", e)
            self._k8s = None
            self._core_k8s = None
            self._k8s_available = False

    def _load_template(self) -> None:
        """Load the KubeVirt VM template for direct provisioning."""
        path = os.environ.get("VM_TEMPLATE_PATH", "")
        if not path:
            for candidate in [
                "/config/vm-template.yaml",
                "deployment/harvester/vm-template.yaml",
            ]:
                if os.path.exists(candidate):
                    path = candidate
                    break

        if not path or not os.path.exists(path):
            logger.info("VM template not found — direct K8s provisioning disabled")
            self._k8s = None
            self._core_k8s = None
            self._k8s_available = False
            return

        with open(path) as f:
            self._template_text = f.read()

        self._k8s_available = True
        logger.info("Loaded VM template from %s", path)

    def _render_template(self, job_config: dict) -> dict:
        """Render the VM template with job-specific values.

        Same string substitution as vm/controller/controller.py.
        """
        owner_kind, owner_id = _owner_identity(job_config)
        replacements = {
            # NOTE: keep _escape_for_job_config() in sync with the copy in
            # vm/controller/controller.py — separate images, no shared code.
            "${JOB_ID}": job_config["job_id"],
            "${OWNER_KIND}": owner_kind,
            "${OWNER_ID}": owner_id,
            "${AGENT_CONFIG}": job_config.get("agent_config", "worker_base"),
            "${VM_IMAGE}": job_config.get("vm_image") or self._default_vm_image,
            "${CPU_CORES}": str(job_config.get("cpu_cores", 8)),
            "${MEMORY}": job_config.get("memory", "16Gi"),
            "${NATS_URL}": job_config.get("nats_url", ""),
            # Direct mode has no VM controller to inject the deployment identity
            # and mesh settings. Read the same existing environment contract the
            # controller/agent provisioners use. An empty Tailscale key is valid:
            # the cloud-init command is explicitly gated on a non-empty value,
            # which is the co-located, no-mesh deployment path.
            "${ORCHESTRATOR_ID}": os.environ.get("ORCHESTRATOR_ID", "").strip(),
            "${HEADSCALE_URL}": os.environ.get("HEADSCALE_URL", ""),
            "${TAILSCALE_AUTH_KEY}": os.environ.get("TAILSCALE_AUTH_KEY", ""),
            "${DESCRIPTION}": _escape_for_job_config(job_config.get("description", "")),
            # CDI DataVolume storage
            "${VM_STORAGE_CLASS}": os.environ.get("VM_STORAGE_CLASS", "local-path"),
            "${VM_DISK_SIZE}": os.environ.get("VM_DISK_SIZE", "20Gi"),
        }

        rendered = self._template_text
        for placeholder, value in replacements.items():
            rendered = rendered.replace(placeholder, value)

        manifest = yaml.safe_load(rendered)
        _stamp_owner_identity(manifest, owner_kind, owner_id)
        if generation := _provision_generation(job_config.get("provision_generation")):
            _stamp_provision_generation(manifest, generation)
        return manifest

    async def _set_vm_context_if_generation(
        self, job_id: str, generation: str, updates: dict
    ) -> bool:
        if not self._db:
            return False
        try:
            return bool(
                await self._db.merge_vm_context_if_provision_generation(
                    job_id, generation, updates
                )
            )
        except Exception:
            logger.exception(
                "Failed to update generation-guarded VM context for job %s", job_id
            )
            return False

