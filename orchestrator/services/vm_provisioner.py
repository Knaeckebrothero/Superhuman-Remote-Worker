    async def _rootdisk_pvc_uid(
        self,
        *,
        owner_id: str,
        owner_kind: str,
        wait: bool,
    ) -> str | None:
        """Read the exact admitted root PVC identity for direct K8s mode."""

        _known, uid = await self._rootdisk_pvc_probe(
            owner_id=owner_id,
            owner_kind=owner_kind,
            wait=wait,
        )
        return uid

    async def _rootdisk_pvc_probe(
        self,
        *,
        owner_id: str,
        owner_kind: str,
        wait: bool,
    ) -> tuple[bool, str | None]:
        """Return ``(known, uid)`` so exact absence is not transport loss."""

        if self._core_k8s is None:
            logger.warning(
                "Rootdisk PVC identity unavailable for %s: CoreV1Api is not initialized",
                owner_id,
            )
            return False, None
        name = f"agent-vm-{owner_id}-rootdisk"
        attempts = max(1, VM_ROOTDISK_PVC_UID_ATTEMPTS if wait else 1)
        exact_absence = False
        for attempt in range(attempts):
            try:
                pvc = await asyncio.to_thread(
                    self._core_k8s.read_namespaced_persistent_volume_claim,
                    name=name,
                    namespace=self._vm_namespace,
                )
            except Exception as exc:
                if getattr(exc, "status", None) != 404:
                    logger.warning(
                        "Rootdisk PVC identity read failed for %s: %s", name, exc
                    )
                    return False, None
                exact_absence = True
            else:
                uid = _admitted_pvc_uid(
                    pvc,
                    expected_name=name,
                    expected_owner_id=owner_id,
                    expected_owner_kind=owner_kind,
                )
                if uid is not None:
                    return True, uid
                return False, None
            if attempt + 1 < attempts and VM_ROOTDISK_PVC_UID_RETRY_SECONDS > 0:
                await asyncio.sleep(VM_ROOTDISK_PVC_UID_RETRY_SECONDS)
        if exact_absence:
            return True, None
        logger.warning(
            "Rootdisk PVC %s was not admitted with the expected immutable identity; "
            "storage attribution will remain unknown",
            name,
        )
        return False, None

    async def _create_direct(
        self,
        job_id: str,
        agent_config: str,
        vm_image: Optional[str],
        cpu_cores: int,
        memory: str,
        description: str,
        provision_generation: str,
    ) -> bool:
        """Create a VM via direct Kubernetes API call."""
        job_config = {
            "job_id": job_id,
            "entity_type": "job",
            "agent_config": agent_config,
            "vm_image": vm_image,
            "cpu_cores": cpu_cores,
            "memory": memory,
            "description": description,
            "provision_generation": provision_generation,
            "nats_url": os.environ.get("NATS_URL", ""),
        }

        try:
            manifest = self._render_template(job_config)
            vm_name = manifest["metadata"]["name"]

            # K8s client is synchronous — run in thread pool
            admitted_vm = await asyncio.to_thread(
                self._k8s.create_namespaced_custom_object,
                group=KUBEVIRT_GROUP,
                version=KUBEVIRT_VERSION,
                namespace=self._vm_namespace,
                plural=KUBEVIRT_PLURAL,
                body=manifest,
            )
            vm_uid = _admitted_vm_uid(admitted_vm, expected_name=vm_name)
            admitted_generation = _admitted_provision_generation(admitted_vm)
            if vm_uid is None or admitted_generation != provision_generation:
                admitted_vm = await asyncio.to_thread(
                    self._k8s.get_namespaced_custom_object,
                    group=KUBEVIRT_GROUP,
                    version=KUBEVIRT_VERSION,
                    namespace=self._vm_namespace,
                    plural=KUBEVIRT_PLURAL,
                    name=vm_name,
                )
                vm_uid = _admitted_vm_uid(admitted_vm, expected_name=vm_name)
                admitted_generation = _admitted_provision_generation(admitted_vm)
            if vm_uid is None:
                raise RuntimeError("Kubernetes admitted VM response lacks metadata.uid")
            if admitted_generation != provision_generation:
                raise RuntimeError(
                    "Kubernetes admitted VM response has another provision generation"
                )

            rootdisk_pvc_uid = await self._rootdisk_pvc_uid(
                owner_id=job_id,
                owner_kind="job",
                wait=True,
            )

            logger.info("VM created (direct): %s (job %s)", vm_name, job_id)
            updates = {
                "status": "created",
                "vm_name": vm_name,
                "vm_uid": vm_uid,
                "namespace": self._vm_namespace,
                "provisioned_by": "direct",
                "identity_authenticated": True,
                "identity_provision_generation": provision_generation,
            }
            if rootdisk_pvc_uid is not None:
                updates["rootdisk_pvc_uid"] = rootdisk_pvc_uid
            await self._set_vm_context_if_generation(
                job_id,
                provision_generation,
                updates,
            )
            return True
        except Exception as e:
            logger.error("Failed to create VM for job %s: %s", job_id, e)
            await self._set_vm_context_if_generation(
                job_id,
                provision_generation,
                {
                    "status": "failed",
                    "error": str(e),
                    "provisioned_by": "direct",
                },
            )
            return False

    async def _delete_direct(
        self,
        job_id: str,
        *,
        provision_generation: str | None = None,
        expected_vm_uid: str | None = None,
        expected_rootdisk_pvc_uid: str | None = None,
    ) -> bool:
        """Delete a VM via direct Kubernetes API call."""
        vm_name = f"agent-vm-{job_id}"

        generation = _provision_generation(provision_generation)
        if generation is None:
            logger.error(
                "Refusing direct delete for %s without a current provision generation",
                job_id,
            )
            return False

        try:
            current_vm = await asyncio.to_thread(
                self._k8s.get_namespaced_custom_object,
                group=KUBEVIRT_GROUP,
                version=KUBEVIRT_VERSION,
                namespace=self._vm_namespace,
                plural=KUBEVIRT_PLURAL,
                name=vm_name,
            )
            if _admitted_provision_generation(current_vm) != generation:
                logger.error(
                    "Refusing direct delete for %s: provision generation changed",
                    job_id,
                )
                return False
            metadata = (
                current_vm.get("metadata") if isinstance(current_vm, Mapping) else None
            )
            vm_uid = (
                _safe_vm_uid(metadata.get("uid"))
                if isinstance(metadata, Mapping)
                else None
            )
            if vm_uid is None:
                logger.error(
                    "Refusing direct delete for %s: admitted VM UID is unavailable",
                    job_id,
                )
                return False
            if expected_vm_uid is not None and vm_uid != expected_vm_uid:
                logger.info(
                    "Captured VM UID superseded for %s; preserving replacement",
                    job_id,
                )
                return False
            if expected_rootdisk_pvc_uid is not None:
                current_rootdisk_uid = await self._rootdisk_pvc_uid(
                    owner_id=job_id,
                    owner_kind="job",
                    wait=False,
                )
                if current_rootdisk_uid != expected_rootdisk_pvc_uid:
                    logger.info(
                        "Captured rootdisk UID superseded for %s; preserving replacement",
                        job_id,
                    )
                    return False
            await asyncio.to_thread(
                self._k8s.delete_namespaced_custom_object,
                group=KUBEVIRT_GROUP,
                version=KUBEVIRT_VERSION,
                namespace=self._vm_namespace,
                plural=KUBEVIRT_PLURAL,
                name=vm_name,
                body={
                    "apiVersion": "v1",
                    "kind": "DeleteOptions",
                    "preconditions": {"uid": vm_uid},
                },
            )

            logger.info("VM deleted (direct): %s (job %s)", vm_name, job_id)
            await self._set_vm_context_if_generation(
                job_id, generation, {"status": "deleted"}
            )
            return True
        except Exception as e:
            if getattr(e, "status", None) == 404:
                logger.debug("VM already deleted: %s (job %s)", vm_name, job_id)
                await self._set_vm_context_if_generation(
                    job_id, generation, {"status": "deleted"}
                )
                return True
            logger.error("Failed to delete VM for job %s: %s", job_id, e)
            return False

    async def _query_direct(
        self,
        job_id: str,
        *,
        entity_type: str = "job",
        absent_generation: str | None = None,
    ) -> Optional[dict]:
        """Query VM status via direct Kubernetes API call."""
        vm_name = f"agent-vm-{job_id}"

        try:
            vm = await asyncio.to_thread(
                self._k8s.get_namespaced_custom_object,
                group=KUBEVIRT_GROUP,
                version=KUBEVIRT_VERSION,
                namespace=self._vm_namespace,
                plural=KUBEVIRT_PLURAL,
                name=vm_name,
            )

            status = vm.get("status", {})
            conditions = status.get("conditions", [])
            ready = any(
                c.get("type") == "Ready" and c.get("status") == "True"
                for c in conditions
            )

            result = {
                "job_id": job_id,
                "vm_name": vm_name,
                "namespace": self._vm_namespace,
                "ready": ready,
                "phase": status.get("printableStatus", "Unknown"),
                "created": status.get("created", False),
            }
            if (vm_uid := _admitted_vm_uid(vm, expected_name=vm_name)) is not None:
                result["vm_uid"] = vm_uid
            generation = _admitted_provision_generation(vm)
            if generation is not None:
                result["provision_generation"] = generation
            if absent_generation is not None:
                rootdisk_known, rootdisk_pvc_uid = await self._rootdisk_pvc_probe(
                    owner_id=job_id,
                    owner_kind=entity_type,
                    wait=False,
                )
                result["rootdisk_identity_known"] = rootdisk_known
            else:
                # The ordinary lifecycle/status path keeps its historical
                # result shape.  Absence authority is opt-in for teardown.
                rootdisk_pvc_uid = await self._rootdisk_pvc_uid(
                    owner_id=job_id,
                    owner_kind=entity_type,
                    wait=False,
                )
            if rootdisk_pvc_uid is not None:
                result["rootdisk_pvc_uid"] = rootdisk_pvc_uid
            if generation is not None and "vm_uid" in result:
                result["_identity_authenticated"] = True
            return result
        except Exception as e:
            if getattr(e, "status", None) == 404 and absent_generation is not None:
                rootdisk_known, rootdisk_pvc_uid = await self._rootdisk_pvc_probe(
                    owner_id=job_id,
                    owner_kind=entity_type,
                    wait=False,
                )
                return {
                    "job_id": job_id,
                    "status": "not_found",
                    "provision_generation": absent_generation,
                    "rootdisk_identity_known": rootdisk_known,
                    **(
                        {"rootdisk_pvc_uid": rootdisk_pvc_uid}
                        if rootdisk_pvc_uid is not None
                        else {}
                    ),
                    "_identity_authenticated": True,
                }
            logger.debug("VM status query failed for job %s: %s", job_id, e)
            return None

    # =========================================================================
    # HTTP controller backend (same-cluster, controller-mediated)
    #
    # The controller still owns KubeVirt RBAC and the VM template; this
    # transport just swaps NATS for HTTP. Status updates that NATS pushed
    # asynchronously now arrive synchronously in the response body, so
    # context updates happen here in the orchestrator instead of via the
    # vm.lifecycle.status subscription.
    #
    # Caveat: in-VM daemon events (register/heartbeat/freeze/resume) are
    # NOT carried by this transport. Same-cluster deployments that need
    # those still need NATS (or a future HTTP webhook from the daemon).
    # =========================================================================

    async def _create_http(
        self,
        job_id: str,
        agent_config: str,
        vm_image: Optional[str],
        cpu_cores: int,
        memory: str,
        description: str,
        entity_type: str = "job",
        set_provisioning: bool = True,
        provision_generation: str | None = None,
    ) -> bool:
        """Create a VM by POSTing to the co-located VM controller.

        ``set_provisioning=False`` marks a golden-poll re-issue: skip the
        interim 'provisioning' context write so the status stays
        ``waiting_golden`` between polls (the response merge below still
        records whatever the controller answered).
        """
        if self._http_client is None:
            return False

        payload: dict[str, Any] = {
            "job_id": job_id,
            "entity_type": entity_type,
            "agent_config": agent_config,
            "cpu_cores": cpu_cores,
            "memory": memory,
            "description": description,
            "nats_url": "",  # No NATS in same-cluster mode
        }
        generation = _provision_generation(provision_generation)
        if self._lifecycle_hmac_secret is not None and generation is None:
            logger.error(
                "Refusing authenticated HTTP VM create for %s %s without a "
                "current provision generation",
                entity_type,
                job_id,
            )
            return False
        if generation is not None:
            payload["provision_generation"] = generation
        if vm_image:
            payload["vm_image"] = vm_image
        payload = sign_payload(
            payload,
            direction="request",
            operation="create",
            secret=self._lifecycle_hmac_secret,
        )
        request_auth = payload.get(AUTH_FIELD)
        request_id = (
            request_auth.get("request_id")
            if isinstance(request_auth, Mapping)
            else None
        )

        try:
            if set_provisioning:
                if generation is not None:
                    await self._set_context_if_generation(
                        entity_type,
                        job_id,
                        generation,
                        {"status": "provisioning"},
                    )
                else:
                    await self._set_context(
                        entity_type, job_id, {"status": "provisioning"}
                    )
            resp = await self._http_client.post("/vms", json=payload)
            data = resp.json()
            if not isinstance(data, Mapping) or not verify_payload(
                data,
                direction="response",
                operation="create",
                secret=self._lifecycle_hmac_secret,
                expected_correlation_id=request_id,
            ):
                raise RuntimeError(
                    "VM controller create response authentication failed"
                )
            resp.raise_for_status()
            data = unsigned_payload(data)

            updates = {
                "status": data.get("status", "created"),
                "vm_name": data.get("vm_name"),
                "namespace": data.get("namespace"),
                "provisioned_by": "http",
            }
            # New controllers return the immutable admitted VM UID. During a
            # rolling upgrade an older controller may omit it; the fresh
            # context reset leaves vm_uid=None so metering classifies that VM
            # as legacy-unknown instead of trusting its reusable name.
            # Deferred-create responses carry telemetry instead of a VM name
            # (golden import progress, or why the mesh VPN is unreachable);
            # surface it for the dispatcher's poll logging and park message.
            for key in (
                "golden",
                "golden_phase",
                "golden_progress",
                "headscale_error",
            ):
                if data.get(key) is not None:
                    updates[key] = data[key]
            response_generation = _provision_generation(
                data.get("provision_generation")
            )
            identity_updates: dict[str, Any] = {}
            if (
                self._lifecycle_hmac_secret is not None
                and response_generation is not None
                and response_generation == generation
            ):
                if (vm_uid := _safe_vm_uid(data.get("vm_uid"))) is not None:
                    identity_updates["vm_uid"] = vm_uid
                if (
                    rootdisk_pvc_uid := _safe_vm_uid(data.get("rootdisk_pvc_uid"))
                ) is not None:
                    identity_updates["rootdisk_pvc_uid"] = rootdisk_pvc_uid
                if identity_updates:
                    identity_updates.update(
                        {
                            "identity_authenticated": True,
                            "identity_provision_generation": response_generation,
                        }
                    )
            if response_generation and response_generation == generation:
                merged = await self._set_context_if_generation(
                    entity_type,
                    job_id,
                    response_generation,
                    {**updates, **identity_updates},
                )
                if not merged:
                    if self._lifecycle_hmac_secret is not None:
                        logger.warning(
                            "Ignoring stale authenticated HTTP create response for "
                            "%s %s",
                            entity_type,
                            job_id,
                        )
                    else:
                        await self._set_context(entity_type, job_id, updates)
            else:
                if self._lifecycle_hmac_secret is not None:
                    logger.warning(
                        "Ignoring authenticated HTTP create response with a stale or "
                        "missing provision generation for %s %s",
                        entity_type,
                        job_id,
                    )
                else:
                    await self._set_context(entity_type, job_id, updates)
            if data.get("status") == "waiting_golden":
                logger.info(
                    "VM create deferred (http): golden %s importing (%s %s)",
                    data.get("golden"),
                    entity_type,
                    job_id,
                )
            elif data.get("status") == "waiting_headscale":
                logger.info(
                    "VM create deferred (http): Headscale unavailable (%s) (%s %s)",
                    data.get("headscale_error"),
                    entity_type,
                    job_id,
                )
            else:
                logger.info(
                    "VM created (http): %s (%s %s)",
                    data.get("vm_name"),
                    entity_type,
                    job_id,
                )
            return True
        except httpx.HTTPStatusError as e:
            error = _extract_http_error(e.response)
            logger.error(
                "VM controller rejected create for %s %s: %s",
                entity_type,
                job_id,
                error,
            )
            failure = {
                "status": "failed",
                "error": error,
                "provisioned_by": "http",
            }
            if generation is not None:
                await self._set_context_if_generation(
                    entity_type, job_id, generation, failure
                )
            else:
                await self._set_context(entity_type, job_id, failure)
            return False
        except Exception as e:
            logger.error("HTTP create failed for %s %s: %s", entity_type, job_id, e)
            failure = {
                "status": "failed",
                "error": str(e),
                "provisioned_by": "http",
            }
            if generation is not None:
                await self._set_context_if_generation(
                    entity_type, job_id, generation, failure
                )
            else:
                await self._set_context(entity_type, job_id, failure)
            return False

    async def _delete_http(
        self,
        job_id: str,
        entity_type: str = "job",
        purge_disk: bool = True,
        provision_generation: str | None = None,
        expected_vm_uid: str | None = None,
        expected_rootdisk_pvc_uid: str | None = None,
    ) -> bool:
        """Delete a VM by sending DELETE to the co-located VM controller."""
        if self._http_client is None:
            return False

        generation = _provision_generation(provision_generation)
        if self._lifecycle_hmac_secret is not None and generation is None:
            logger.error(
                "Refusing authenticated HTTP VM delete for %s without a current "
                "provision generation",
                job_id,
            )
            return False
        signed_payload = {
            "job_id": job_id,
            "purge_disk": purge_disk,
            "provision_generation": generation,
        }
        if expected_vm_uid is not None:
            signed_payload["expected_vm_uid"] = expected_vm_uid
        if expected_rootdisk_pvc_uid is not None:
            signed_payload["expected_rootdisk_pvc_uid"] = expected_rootdisk_pvc_uid
        params: dict[str, str] = {}
        if not purge_disk:
            params["purge_disk"] = "false"
        if generation is not None:
            params["provision_generation"] = generation
        if expected_vm_uid is not None:
            params["expected_vm_uid"] = expected_vm_uid
        if expected_rootdisk_pvc_uid is not None:
            params["expected_rootdisk_pvc_uid"] = expected_rootdisk_pvc_uid
        params.update(
            _http_lifecycle_query(
                signed_payload,
                operation="delete",
                secret=self._lifecycle_hmac_secret,
            )
        )
        request_id = params.get("lifecycle_auth_request_id")
        try:
            resp = await self._http_client.delete(f"/vms/{job_id}", params=params)
            data: Mapping[str, Any] | None = None
            if self._lifecycle_hmac_secret is not None or resp.status_code != 404:
                candidate = resp.json()
                if not isinstance(candidate, Mapping) or not verify_payload(
                    candidate,
                    direction="response",
                    operation="delete",
                    secret=self._lifecycle_hmac_secret,
                    expected_correlation_id=request_id,
                ):
                    raise RuntimeError(
                        "VM controller delete response authentication failed"
                    )
                data = unsigned_payload(candidate)
            if resp.status_code != 404:
                resp.raise_for_status()
            if self._lifecycle_hmac_secret is not None:
                response_generation = _provision_generation(
                    data.get("provision_generation") if data else None
                )
                if response_generation != generation:
                    raise RuntimeError(
                        "VM controller delete response generation mismatch"
                    )
            if generation is not None:
                await self._set_context_if_generation(
                    entity_type, job_id, generation, {"status": "deleted"}
                )
            else:
                await self._set_context(entity_type, job_id, {"status": "deleted"})
            logger.info("VM deleted (http): %s %s", entity_type, job_id)
            return True
        except httpx.HTTPStatusError as e:
            error = _extract_http_error(e.response)
            logger.error(
                "VM controller rejected delete for %s %s: %s",
                entity_type,
                job_id,
                error,
            )
            return False
        except Exception as e:
            logger.error("HTTP delete failed for %s %s: %s", entity_type, job_id, e)
            return False

    async def _query_http(
        self,
        job_id: str,
        timeout: float = 5.0,
        provision_generation: str | None = None,
        *,
        exact_absence: bool = False,
    ) -> Optional[dict]:
        """Query VM status via the co-located VM controller."""
        if self._http_client is None:
            return None

        generation = _provision_generation(provision_generation)
        if self._lifecycle_hmac_secret is not None and generation is None:
            return None
        signed_payload = {
            "job_id": job_id,
            "provision_generation": generation,
        }
        params: dict[str, str] = {}
        if generation is not None:
            params["provision_generation"] = generation
        if exact_absence:
            signed_payload["exact_absence"] = True
            params["exact_absence"] = "true"
        params.update(
            _http_lifecycle_query(
                signed_payload,
                operation="status",
                secret=self._lifecycle_hmac_secret,
            )
        )
        request_id = params.get("lifecycle_auth_request_id")
        try:
            resp = await self._http_client.get(
                f"/vms/{job_id}", params=params, timeout=timeout
            )
            data = resp.json()
            if not isinstance(data, Mapping) or not verify_payload(
                data,
                direction="response",
                operation="status",
                secret=self._lifecycle_hmac_secret,
                expected_correlation_id=request_id,
            ):
                return None
            result = unsigned_payload(data)
            if (
                self._lifecycle_hmac_secret is not None
                and _provision_generation(result.get("provision_generation"))
                != generation
            ):
                return None
            if resp.status_code == 404:
                return None
            resp.raise_for_status()
            if self._lifecycle_hmac_secret is not None:
                result["_identity_authenticated"] = True
            return result
        except Exception as e:
            logger.debug("HTTP status query failed for job %s: %s", job_id, e)
            return None

    async def _list_http(
        self, *, include_teardown_identity: bool = False
    ) -> Optional[list]:
        """List managed VMs via the co-located VM controller.

        A 404 means the controller predates the list op — unknown, not empty.
        """
        if self._http_client is None:
            return None

        try:
            signed_payload = {
                **(
                    {"include_teardown_identity": True}
                    if include_teardown_identity
                    else {}
                )
            }
            params = _http_lifecycle_query(
                signed_payload, operation="list", secret=self._lifecycle_hmac_secret
            )
            if include_teardown_identity:
                params["include_teardown_identity"] = "true"
            resp = await self._http_client.get(
                "/vms",
                params=params,
            )
            if resp.status_code == 404:
                return None
            resp.raise_for_status()
            data = resp.json()
            if not isinstance(data, Mapping) or not verify_payload(
                data,
                direction="response",
                operation="list",
                secret=self._lifecycle_hmac_secret,
                expected_correlation_id=params.get("lifecycle_auth_request_id"),
            ):
                return None
            vms = unsigned_payload(data).get("vms")
            return vms if isinstance(vms, list) else None
        except Exception as e:
            logger.debug("HTTP VM list failed: %s", e)
            return None

    async def _list_direct(
        self, *, include_teardown_identity: bool = False
    ) -> Optional[list]:
        """List managed VMs via direct Kubernetes API call.

        Mirrors the controller's ``_do_list``: agent VMs only, golden
        DataVolume names excluded as defense-in-depth.
        """
        try:
            vms = await asyncio.to_thread(
                self._k8s.list_namespaced_custom_object,
                group=KUBEVIRT_GROUP,
                version=KUBEVIRT_VERSION,
                namespace=self._vm_namespace,
                plural=KUBEVIRT_PLURAL,
            )
        except Exception as e:
            logger.debug("Direct VM list failed: %s", e)
            return None

        out = []
        for item in vms.get("items", []):
            meta = item.get("metadata", {})
            name = meta.get("name", "")
            if not name.startswith("agent-vm-") or name.startswith("agent-vm-golden-"):
                continue
            entity_id = name[len("agent-vm-") :]
            inventory = {
                "vm_name": name,
                "entity_id": entity_id,
                "created_at": meta.get("creationTimestamp"),
                "phase": item.get("status", {}).get("printableStatus", "Unknown"),
            }
            if include_teardown_identity:
                generation = _admitted_provision_generation(item)
                vm_uid = _admitted_vm_uid(item, expected_name=name)
                rootdisk_uid = await self._rootdisk_pvc_uid(
                    owner_id=entity_id,
                    owner_kind=None,
                    wait=False,
                )
                if generation is not None:
                    inventory["provision_generation"] = generation
                if vm_uid is not None:
                    inventory["vm_uid"] = vm_uid
                if rootdisk_uid is not None:
                    inventory["rootdisk_pvc_uid"] = rootdisk_uid
            out.append(inventory)
        return out

    async def _set_context(
        self, entity_type: str, entity_id: str, updates: dict
    ) -> None:
        """Route context updates to the right table based on entity type."""
        if entity_type == "thread":
            await self._set_thread_vm_context(entity_id, updates)
        else:
            await self._set_vm_context(entity_id, updates)

    # =========================================================================
    # Helpers
    # =========================================================================

    @staticmethod
    def _fresh_provision_ctx() -> dict:
        """Reap-counter/endpoint reset + provision timestamp for a new VM.

        Merged into context.vm at the start of every (re)provision so the new
        incarnation does not inherit the previous one's snapshot_attempts (which
        would make the lifecycle reaper's attempts_exhausted instantly true), a
        dead ssh_host, or stale SSH-readiness probe identity. ``provisioned_at``
        (epoch seconds) anchors the dispatcher's provisioning-timeout escalation.
        """
        return {
            "snapshot_attempts": 0,
            "ssh_host": None,
            "ssh_port": None,
            "ssh_registration_id": None,
            "registered_at": None,
            "ssh_verified_at": None,
            "ssh_probe_attempts": 0,
            "ssh_probe_error": None,
            "ssh_probe_failed_at": None,
            # Never let a previous VM incarnation's UID authenticate the next
            # one between create dispatch and the admitted controller result.
            "vm_uid": None,
            # A PVC name is reusable.  Only the newly admitted immutable UID
            # may authenticate this incarnation's rootdisk for metering.
            "rootdisk_pvc_uid": None,
            "identity_authenticated": False,
            "identity_provision_generation": None,
            # Opaque incarnation nonce. Controller identities are merged only
            # through a DB-side compare-and-merge against this exact value.
            "provision_generation": str(uuid4()),
            # Slice 1 does not trust a guest self-reported VM host key. Keep
            # Canvas closed until the VM provisioner can attest the key.
            CANVAS_WORKSPACE_GENERATION_KEY: None,
            # Golden-wait anchor from a previous incarnation must not cap this
            # provision's patience for a cold golden import (dispatcher stamps
            # it again on the first waiting_golden it sees). Same for the
            # Headscale-wait anchor.
            "golden_wait_started_at": None,
            "headscale_wait_started_at": None,
            # Same for the teardown anchor: a stale one would make this
            # incarnation read as instantly-stuck the moment it enters
            # 'deleting', and the dispatcher would recycle it on sight.
            "deleting_started_at": None,
            "headscale_error": None,
            "provisioned_at": time.time(),
        }

    async def _set_vm_context(self, job_id: str, updates: dict) -> None:
        """Atomically merge updates into the job's context.vm key."""
        if not self._db:
            return

        try:
            await self._db.merge_vm_context(job_id, updates)
        except Exception:
            logger.exception("Failed to update VM context for job %s", job_id)

