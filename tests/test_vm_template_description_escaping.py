"""Regression: a job description must not be able to corrupt the VM manifest.

A job description is free text — typed by users, generated by the loop engine
and automations. It is substituted into a JSON blob that lives inside the
`cloudInitNoCloud.userData: |` *block scalar* of the VM template, which makes
raw substitution fragile in two different ways:

  1. A newline (even a single trailing blank line) puts the continuation at
     column 1, which dedents out of the block scalar and terminates it. YAML
     then parses the description's tail as outer mapping keys and provisioning
     dies. Job 4435994d (2026-07-26) failed exactly this way — its description
     ended with a blank line.
  2. A `"` or `\\` does NOT break the YAML at all. The manifest applies, the VM
     boots, and job-config.json is corrupt — which management-daemon.py
     swallows with a log.warning, silently losing agent_config/vm_image/etc.
     A description shaped like indented YAML reaches the cloud-init structure
     the same way, producing a manifest that passes yaml.safe_load and is
     accepted by KubeVirt while its userData is malformed.

The parked external vm-controller render site remains covered. Same-cluster
mode no longer has a direct-K8s renderer and its job-config intentionally omits
the unused description field.

These tests render the REAL chart templates rather than a simplified fixture.
That is deliberate: the defect lives in the real template's *structure*, so the
hand-written stand-in templates in test_vm_provisioner.py and
test_vm_controller.py — which put the description in a plain flow scalar with
no block scalar and no JSON blob — cannot express it. They both have a
"special characters in description" test today, and both passed throughout.
"""

import json
import re
import sys
import textwrap
import types
from pathlib import Path
from unittest.mock import AsyncMock, MagicMock

import pytest
import yaml

PROJECT_ROOT = Path(__file__).parent.parent

# The same-cluster template mounts cloud-init from a Secret (no KubeVirt
# 2048-byte inline cap), but the controller still truncates the description and
# the whole payload must stay within the chart's own sanity budget — the same
# bound test_vm_chart_manifest_contract.py holds the rendered chart to.
USER_DATA_LIMIT = 16 * 1024

MAIN_CHART_CONFIGMAP = "helm/templates/vm-controller/configmap.yaml"

JOB_CONFIG_PATH = "/run/agent/job-config.json"


# =============================================================================
# Loading the real template out of the Helm ConfigMap
# =============================================================================


def _load_chart_vm_template(rel_path: str, block_key: str = "vm-template.yaml") -> str:
    """Return one plain block-scalar text embedded in a Helm ConfigMap.

    Drops Helm comment blocks, substitutes a dummy for remaining Helm value
    expressions, then extracts and dedents the `<block_key>: |` block
    scalar — leaving exactly the text the provisioner loads at runtime, with
    its ${...} placeholders intact.
    """
    text = (PROJECT_ROOT / rel_path).read_text()
    # Helm comments — {{- /* ... */ -}} — may span lines.
    text = re.sub(r"\{\{-?\s*/\*.*?\*/\s*-?\}\}", "", text, flags=re.DOTALL)

    lines = text.splitlines()
    start = next(i for i, ln in enumerate(lines) if f"{block_key}: |" in ln) + 1

    # The block scalar runs until the first non-blank line that is not indented
    # past the block's own indentation (e.g. the chart's trailing {{- end }}).
    first_body = next(ln for ln in lines[start:] if ln.strip())
    indent = first_body[: len(first_body) - len(first_body.lstrip())]

    body = []
    for ln in lines[start:]:
        if ln.strip() and not ln.startswith(indent):
            break
        body.append(ln)

    template = textwrap.dedent("\n".join(body))
    # Any Helm value expression left inside the block (e.g. the SSH pubkey).
    return re.sub(
        r"\{\{.*?\}\}", "ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIdummytestkey", template
    )


# =============================================================================
# Pulling the rendered cloud-init back apart
# =============================================================================


def _user_data(manifest: dict) -> str:
    """Extract the rendered cloud-init userData for the VM.

    The same-cluster template mounts cloud-init from a Secret; the controller
    hands the rendered payload back on the manifest for the Secret write.
    """
    return manifest["_srwCloudInitUserData"]


def _job_config(manifest: dict) -> dict:
    """Parse /run/agent/job-config.json back out of a rendered VM manifest.

    Fails the test if the JSON is corrupt — that is the silent-corruption mode
    the escaping exists to prevent.
    """
    files = yaml.safe_load(_user_data(manifest))["write_files"]
    blob = next(f for f in files if f["path"] == JOB_CONFIG_PATH)["content"]
    try:
        return json.loads(blob)
    except json.JSONDecodeError as exc:
        pytest.fail(f"job-config.json is not valid JSON on the VM: {exc}\n{blob}")


def _write_file_paths(manifest: dict) -> list:
    return [f["path"] for f in yaml.safe_load(_user_data(manifest))["write_files"]]


def _runcmd(manifest: dict) -> list:
    return yaml.safe_load(_user_data(manifest)).get("runcmd", [])


